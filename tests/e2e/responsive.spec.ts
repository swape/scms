test('preview size switches between desktop, tablet, and phone without reloading the iframe', async ({ page, project }) => {
  project.pages[0].content[0].style = { paddingAll: '40px' }
  project.pages[0].content[0].mobileStyle = { paddingAll: '8px' }
  await seedProject(page, project)
  await page.goto('/editor?p=1&local=true')

  const block = preview(page).locator('section[data-id="text"]')
  const desktop = page.getByRole('button', { name: 'Desktop preview', exact: true })
  const tablet = page.getByRole('button', { name: 'Tablet preview', exact: true })
  const phone = page.getByRole('button', { name: 'Phone preview', exact: true })
  const iframe = page.getByTitle('Preview', { exact: true })
  const previewWidth = () => iframe.evaluate((frame) => frame.clientWidth)

  await expect(desktop).toBeVisible()
  await expect(block).toHaveCSS('padding', '40px')
  const desktopWidth = await previewWidth()
  expect(desktopWidth).toBeGreaterThan(768)
  await block.evaluate((element) => element.setAttribute('data-resize-test', 'same-document'))

  await desktop.click()
  await expect(tablet).toBeFocused()
  await expect.poll(previewWidth).toBe(768)
  await expect(block).toHaveCSS('padding', '8px')

  await tablet.press('Space')
  await expect(phone).toBeFocused()
  await expect.poll(previewWidth).toBe(390)
  await expect(block).toHaveCSS('padding', '8px')

  await phone.click()
  await expect.poll(previewWidth).toBe(desktopWidth)
  await expect(block).toHaveCSS('padding', '40px')
  await expect(block).toHaveAttribute('data-resize-test', 'same-document')

  await desktop.click()
  await page.setViewportSize({ width: 360, height: 800 })
  await expect.poll(previewWidth).toBeLessThan(360)
  await expect(block).toHaveCSS('padding', '8px')
  await page.reload()
  await expect(desktop).toBeVisible()
})

test('inline margins render independently and inherit normal values in mobile mode', async ({ editorPage: page }) => {
  await selectBlock(page, 'text')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  const margins = page.getByRole('group', { name: 'Margin Inline:' })
  const start = margins.getByRole('spinbutton', { name: 'Start', exact: true })
  const end = margins.getByRole('spinbutton', { name: 'End', exact: true })
  const block = preview(page).locator('section[data-id="text"]')

  await page.getByLabel('Wrapper:').selectOption('container')
  await start.fill('24')
  await end.fill('2')
  await margins.getByLabel('End unit').selectOption('rem')
  await expect(block).toHaveCSS('margin-inline-start', '24px')
  await expect(block).toHaveCSS('margin-inline-end', '32px')

  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(start).toHaveValue('24')
  await expect(end).toHaveValue('2')
  await start.fill('0')
  await page.getByLabel('Wrapper:').selectOption('')
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].mobileStyle).toEqual({ marginInlineStart: '0px', wrapper: '' })
  await page.getByRole('button', { name: 'Desktop preview', exact: true }).click()
  await expect(block).toHaveCSS('max-width', 'none')
  await expect(block).toHaveCSS('margin-inline-start', '0px')
  await expect(block).toHaveCSS('margin-inline-end', '32px')

  await page.reload()
  await selectBlock(page, 'text')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  await expect(margins.getByLabel('End unit')).toHaveValue('rem')
  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(start).toHaveValue('0')
  await start.fill('')
  await expect(start).toHaveValue('24')
  await page.getByRole('button', { name: 'Desktop preview', exact: true }).click()
  await expect(block).toHaveCSS('margin-inline-start', '24px')
  await expect(block).toHaveCSS('margin-inline-end', '32px')
})

test('auto inline margins center a constrained block and can be overridden on mobile', async ({ editorPage: page }) => {
  await page.setViewportSize({ width: 1900, height: 1000 })
  await selectBlock(page, 'text')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  const start = page.getByLabel('Start', { exact: true })
  const startUnit = page.getByLabel('Start unit', { exact: true })
  const endUnit = page.getByLabel('End unit', { exact: true })
  const block = preview(page).locator('section[data-id="text"]')

  await page.getByLabel('Wrapper:').selectOption('container')
  await startUnit.selectOption('auto')
  await endUnit.selectOption('auto')
  await expect(start).toBeDisabled()
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].style).toMatchObject({ marginInlineStart: 'auto', marginInlineEnd: 'auto' })
  await expect
    .poll(() =>
      block.evaluate((element) => {
        const { marginLeft, marginRight } = getComputedStyle(element)
        return parseFloat(marginLeft) > 0 && marginLeft === marginRight
      })
    )
    .toBe(true)

  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(startUnit).toHaveValue('auto')
  await startUnit.selectOption('px')
  await expect(start).toBeEnabled()
  await start.fill('16')
  await page.getByLabel('Wrapper:').selectOption('')
  await page.getByRole('button', { name: 'Desktop preview', exact: true }).click()
  await expect(block).toHaveCSS('margin-inline-start', '16px')
  await expect.poll(() => block.evaluate((element) => element.computedStyleMap().get('margin-inline-end')?.toString())).toBe('auto')

  await start.clear()
  await expect(startUnit).toHaveValue('auto')
})

test('mobile padding stays sparse, applies through 768px, and resumes inheritance after clearing or reset', async ({ editorPage: page }) => {
  await selectBlock(page, 'text')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  const normal = page.getByRole('tab', { name: 'Normal', exact: true })
  const mobile = page.getByRole('tab', { name: 'Mobile overrides', exact: true })
  const padding = page.getByLabel('Padding:', { exact: true })
  await expect(normal).toHaveAttribute('aria-selected', 'true')
  await padding.fill('24')
  await mobile.click()
  await expect(padding).toHaveValue('24')
  await padding.fill('0')
  await expect(mobile).toHaveAttribute('aria-selected', 'true')
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].mobileStyle).toEqual({ paddingAll: '0px' })

  await normal.click()
  await expect(padding).toHaveValue('24')
  await padding.fill('40')
  await mobile.click()
  await expect(padding).toHaveValue('0')
  await selectBlock(page, 'text')
  await expect(mobile).toHaveAttribute('aria-selected', 'true')
  await selectBlock(page, 'header')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  await expect(normal).toHaveAttribute('aria-selected', 'true')
  await selectBlock(page, 'text')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  await expect(normal).toHaveAttribute('aria-selected', 'true')
  await expect(padding).toHaveValue('40')
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].style?.paddingAll).toBe('40px')

  // A top-level preview measures the actual CSS viewport, not the editor's outer width.
  await openPreview(page, await storedProject(page))
  const block = page.locator('section[data-id="text"]')
  await page.setViewportSize({ width: 769, height: 1000 })
  await expect(block).toHaveCSS('padding', '40px')
  await page.setViewportSize({ width: 768, height: 1000 })
  await expect(block).toHaveCSS('padding', '0px')

  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/editor?p=1&local=true')
  await selectBlock(page, 'text')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  await mobile.click()
  await padding.fill('')
  await expect(padding).toHaveValue('40')
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].mobileStyle?.paddingAll).toBeUndefined()
  await padding.fill('8')
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].mobileStyle).toEqual({ paddingAll: '8px' })
  await page.getByRole('button', { name: 'Reset mobile overrides', exact: true }).click()
  await expect(padding).toHaveValue('40')
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].mobileStyle ?? {}).toEqual({})
  await normal.click()
  await padding.fill('48')
  await mobile.click()
  await expect(padding).toHaveValue('48')
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].style?.paddingAll).toBe('48px')
  await expect.poll(async () => (await storedProject(page)).pages[0].content[0].mobileStyle ?? {}).toEqual({})
  await openPreview(page, await storedProject(page))
  await page.setViewportSize({ width: 768, height: 1000 })
  await expect(block).toHaveCSS('padding', '48px')
})

test('page and menu mobile palettes and layout survive JSON restore and reload without losing content', async ({ editorPage: page }) => {
  await selectBlock(page, 'text')
  await page.getByLabel('Content:', { exact: true }).fill('Content survives mobile palette edits')
  await page.locator('.page-button').filter({ hasText: 'Home page' }).click()
  await page.getByLabel('Title:', { exact: true }).fill('Palette home')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  await page.getByLabel('Page background color:').selectOption('bg_2')
  await page.getByLabel('Page text color:').selectOption('text_2')
  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(page.getByLabel('Page background color:')).toHaveValue('bg_2')
  await page.getByLabel('Page background color:').selectOption('bg_3')
  await page.getByLabel('Page text color:').selectOption('text_3')

  await preview(page).locator('[data-items="menu"]').click()
  const firstItem = page.getByRole('list', { name: 'Menu items', exact: true }).locator(':scope > li').first()
  await firstItem.getByLabel('Label', { exact: true }).fill('Start here')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Normal', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(page.getByLabel('Layout', { exact: true })).toHaveValue('horizontal')
  await page.getByLabel('Layout', { exact: true }).selectOption('vertical')
  await page.getByLabel('Background color:', { exact: true }).selectOption('bg_2')
  await page.getByLabel('Text color:', { exact: true }).selectOption('text_2')
  await expect.poll(async () => (await storedProject(page)).menu.mobileStyle).toEqual({ layout: 'vertical', backgroundColor: 'bg_2', textColor: 'text_2' })

  await page.getByRole('button', { name: 'Save & load', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save as JSON', exact: true }).click()
  const file = await (await downloadPromise).path()
  expect(file).not.toBeNull()
  const exported: ProjectType = JSON.parse(await readFile(file!, 'utf8'))
  expect(exported.pages[0].title).toBe('Palette home')
  expect(exported.pages[0].content[0].content).toBe('Content survives mobile palette edits')
  expect(exported.pages[0].colors).toEqual({ backgroundColorKey: 'bg_2', textColorKey: 'text_2' })
  expect(exported.pages[0].mobileStyle).toEqual({ backgroundColorKey: 'bg_3', textColorKey: 'text_3' })
  expect(exported.menu.style).toEqual({ layout: 'horizontal', backgroundColor: 'bg_1', textColor: 'text_1' })
  expect(exported.menu.mobileStyle).toEqual({ layout: 'vertical', backgroundColor: 'bg_2', textColor: 'text_2' })
  expect(exported.menu.elements[0].title).toBe('Start here')

  await page.getByLabel('Layout', { exact: true }).selectOption('horizontal')
  await expect.poll(async () => (await storedProject(page)).menu.mobileStyle?.layout).toBe('horizontal')
  page.once('dialog', (dialog) => dialog.accept())
  const imported = page.waitForEvent('load')
  await page.getByLabel('Project JSON file', { exact: true }).setInputFiles(file!)
  await imported
  await page.reload()
  await expect(page.locator('.page-button').filter({ hasText: 'Palette home' })).toBeVisible()
  await expect(preview(page).locator('section[data-id="text"] p')).toHaveText('Content survives mobile palette edits')
  await expect.poll(() => storedProject(page)).toEqual(exported)

  await openPreview(page, await storedProject(page))
  const menu = page.getByRole('navigation', { name: 'Project menu' })
  const menuContainer = page.locator('[data-items="menu"]')
  await page.setViewportSize({ width: 769, height: 1000 })
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(241, 245, 249)')
  await expect(page.locator('body')).toHaveCSS('color', 'rgb(71, 85, 105)')
  await expect(menu.locator(':scope > ul')).toHaveCSS('flex-direction', 'row')
  await expect(menuContainer).toHaveCSS('background-color', 'rgb(248, 250, 252)')
  await expect(menu.getByRole('link', { name: 'Start here', exact: true })).toHaveCSS('color', 'rgb(15, 23, 42)')
  await page.setViewportSize({ width: 768, height: 1000 })
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(99, 102, 241)')
  await expect(page.locator('body')).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(menu.locator(':scope > ul')).toHaveCSS('flex-direction', 'column')
  await expect(menuContainer).toHaveCSS('background-color', 'rgb(241, 245, 249)')
  await expect(menu.getByRole('link', { name: 'Start here', exact: true })).toHaveCSS('color', 'rgb(71, 85, 105)')
  await expect(menu.getByRole('link', { name: 'Start here', exact: true })).toHaveAttribute('href', '#page-home')
  await expect(page.locator('section[data-id="text"] p')).toHaveText('Content survives mobile palette edits')
})

test('an explicit mobile false renders a normal button as an inline link', async ({ page, project }) => {
  const linkBlock = project.pages[0].content.find((block) => block.id === 'link')!
  linkBlock.link = { ...linkBlock.link!, asButton: true, style: { buttonColor: 'bg_3', buttonTextColor: 'text_3' } }
  await seedProject(page, project)
  await page.goto('/editor?p=1&local=true')
  await selectBlock(page, 'link')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  const asButton = page.getByRole('switch', { name: 'Render as button', exact: true })
  await expect(asButton).toBeChecked()
  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(asButton).toBeChecked()
  await asButton.press('Space')
  await expect(asButton).not.toBeChecked()
  await expect.poll(async () => (await storedProject(page)).pages[0].content.find((block) => block.id === 'link')?.mobileStyle).toEqual({ asButton: false })
  await page.getByRole('tab', { name: 'Normal', exact: true }).click()
  await expect(asButton).toBeChecked()
  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(asButton).not.toBeChecked()

  await openPreview(page, await storedProject(page))
  const link = page.locator('section[data-id="link"] a')
  await page.setViewportSize({ width: 769, height: 1000 })
  await expect(link).toHaveCSS('padding', '10.4px 16px')
  await expect(link).toHaveCSS('text-decoration-line', 'none')
  await expect(link).toHaveCSS('background-color', 'rgb(99, 102, 241)')
  await expect(link).toHaveCSS('color', 'rgb(255, 255, 255)')
  await page.setViewportSize({ width: 768, height: 1000 })
  await expect(link).toHaveCSS('padding', '0px')
  await expect(link).toHaveCSS('text-decoration-line', 'underline')
  await expect(link).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(link).toHaveCSS('color', 'rgb(15, 23, 42)')
  await expect(link).toHaveAttribute('href', 'https://example.com/read')
})

test('mobile split controls clear a wrapper, unflip sides, and inherit untouched individual padding', async ({ page, project }) => {
  const splitBlock = project.pages[0].content.find((block) => block.id === 'splitBlock')!
  splitBlock.flipped = true
  splitBlock.style = { wrapper: 'container', paddingMode: 'individual', paddingTop: '11px', paddingRight: '12px', paddingBottom: '13px', paddingLeft: '14px' }
  await seedProject(page, project)
  await page.goto('/editor?p=1&local=true')
  await selectBlock(page, 'splitBlock')
  await page.getByRole('tab', { name: 'Style', exact: true }).click()
  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(page.getByLabel('Wrapper:', { exact: true })).toHaveValue('container')
  await page.getByLabel('Wrapper:', { exact: true }).selectOption('')
  await page.getByRole('switch', { name: 'Flip sides (image on left)', exact: true }).press('Space')
  await expect(page.getByLabel('Padding Mode:', { exact: true })).toHaveValue('individual')
  await page.locator('#padding-right').fill('0')
  await page.getByRole('tab', { name: 'Normal', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Flip sides (image on left)', exact: true })).toBeChecked()
  await expect(page.getByLabel('Wrapper:', { exact: true })).toHaveValue('container')
  await expect(page.locator('#padding-right')).toHaveValue('12')
  await page.locator('#padding-left').fill('20')
  await page.getByRole('tab', { name: 'Mobile overrides', exact: true }).click()
  await expect(page.locator('#padding-left')).toHaveValue('20')
  await expect(page.locator('#padding-right')).toHaveValue('0')
  await expect
    .poll(async () => (await storedProject(page)).pages[0].content.find((block) => block.id === 'splitBlock')?.mobileStyle)
    .toEqual({ wrapper: '', flipped: false, paddingRight: '0px' })
  await expect.poll(async () => (await storedProject(page)).pages[0].content.find((block) => block.id === 'splitBlock')?.style?.paddingLeft).toBe('20px')

  await openPreview(page, await storedProject(page))
  const section = page.locator('section[data-id="splitBlock"]')
  const split = section.locator('.split-block')
  const text = section.locator('.split-text')
  const image = section.locator('.split-image')
  await page.setViewportSize({ width: 769, height: 1000 })
  await expect(section).toHaveCSS('max-width', '1024px')
  await expect(split).toHaveCSS('padding', '11px 12px 13px 20px')
  await expect.poll(async () => (await text.boundingBox())!.x > (await image.boundingBox())!.x).toBe(true)
  await page.setViewportSize({ width: 768, height: 1000 })
  await expect(section).toHaveCSS('max-width', 'none')
  await expect(split).toHaveCSS('padding', '11px 0px 13px 20px')
  await expect.poll(async () => (await text.boundingBox())!.x < (await image.boundingBox())!.x).toBe(true)
})
