test('Link switches URL/page destinations, targets, and button appearance', async ({ editorPage: page }) => {
  await selectBlock(page, 'link')
  await page.getByLabel('Text:', { exact: true }).fill('Visit example')
  await page.getByLabel('URL:', { exact: true }).fill('https://example.com/updated')
  await page.getByLabel('Target:', { exact: true }).selectOption('_blank')
  await page.getByRole('switch', { name: 'Render as button' }).press('Space')
  const link = () => preview(page).locator('section[data-id="link"] a')
  await expect(link()).toHaveText('Visit example')
  await expect(link()).toHaveAttribute('href', 'https://example.com/updated')
  await expect(link()).toHaveAttribute('target', '_blank')
  await expect(link()).toHaveAttribute('rel', 'noopener noreferrer')
  await expect(link()).toHaveClass('link-button')
  await page.getByLabel('Button color:', { exact: true }).selectOption('bg_3')
  await page.getByLabel('Button text color:', { exact: true }).selectOption('text_3')
  await expect(link()).toHaveCSS('background-color', 'rgb(99, 102, 241)')
  await expect(link()).toHaveCSS('color', 'rgb(255, 255, 255)')
  await page.getByLabel('Destination Type:', { exact: true }).selectOption('page')
  await page.getByLabel('Page:', { exact: true }).selectOption('about')
  await page.getByLabel('Target:', { exact: true }).selectOption('_self')
  await page.getByRole('switch', { name: 'Render as button' }).press('Space')
  await expect(link()).toHaveAttribute('href', '#page-about')
  await expect(link()).toHaveAttribute('target', '_self')
  await expect(link()).not.toHaveAttribute('rel')
  await expect(link()).toHaveClass('link-inline')
})

test('Split Block edits content, file, CTA, flipping, and image minimum height', async ({ editorPage: page }) => {
  await selectBlock(page, 'splitBlock')
  await page.getByLabel('Text block title:').fill('Updated feature')
  await page.getByLabel('Text block content:').fill('Updated feature body')
  await page.getByLabel('Button text:').fill('Open about')
  await page.getByLabel('Destination type:', { exact: true }).selectOption('page')
  await page.getByLabel('Page:', { exact: true }).selectOption('about')
  await page.getByLabel('Target:', { exact: true }).selectOption('_blank')
  await page.getByRole('switch', { name: 'Flip sides (image on left)' }).press('Space')
  await page.getByLabel('Image minimum height (px):').fill('420')
  await page.getByLabel('Text padding (px):').fill('32')
  await page.getByLabel('Border radius (px):').fill('16')
  await page.getByRole('button', { name: 'Select file', exact: true }).click()
  await page
    .locator('#file-popover-wrapper')
    .getByRole('button', { name: /folder2$/ })
    .click()
  await page.locator('#file-popover-wrapper').getByRole('button', { name: 'File 3', exact: true }).click()
  const block = () => preview(page).locator('section[data-id="splitBlock"]')
  await expect(block().getByRole('heading', { name: 'Updated feature' })).toBeVisible()
  await expect(block().locator('p')).toHaveText('Updated feature body')
  await expect(block().locator('.split-block')).toHaveClass(/split-block-flipped/)
  await expect(block().locator('.split-block')).toHaveCSS('border-radius', '16px')
  await expect(block().locator('.split-image')).toHaveCSS('min-height', '420px')
  await expect(block().locator('.split-text')).toHaveCSS('padding', '32px')
  await expect(block().getByRole('img', { name: 'File 3' })).toHaveCSS('background-image', /600x1400/)
  await expect(block().getByRole('link', { name: 'Open about' })).toHaveAttribute('href', '#page-about')
  await expect(block().getByRole('link', { name: 'Open about' })).toHaveAttribute('rel', 'noopener noreferrer')
  await page.reload()
  await expect(block().locator('.split-image')).toHaveCSS('min-height', '420px')
  await selectBlock(page, 'splitBlock')
  await expect(page.getByLabel('Image minimum height (px):')).toHaveValue('420')
})
