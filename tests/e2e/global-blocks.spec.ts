test('Menu adds nested items, reorders, removes, and stays project-global', async ({ editorPage: page }) => {
  await preview(page).locator('[data-items="menu"]').click()
  await expect(page.getByRole('heading', { name: 'Menu for Test project' })).toBeVisible()
  const items = page.getByRole('list', { name: 'Menu items', exact: true }).locator(':scope > li')
  await items.nth(1).getByRole('button', { name: 'Link', exact: true }).click()
  await expect.poll(async () => (await storedProject(page)).menu.elements[1].children?.length).toBe(2)
  await page.locator('.menu-add-actions').getByRole('button', { name: 'Manual submenu', exact: true }).click()
  await expect.poll(async () => (await storedProject(page)).menu.elements.length).toBe(4)
  await items.last().getByLabel('Label', { exact: true }).fill('Extra submenu')
  await page.getByRole('button', { name: 'Move Extra submenu up', exact: true }).click()
  await expect.poll(async () => (await storedProject(page)).menu.elements[2].title).toBe('Extra submenu')
  await items
    .filter({ has: page.getByRole('button', { name: 'Move Extra submenu up', exact: true }) })
    .getByRole('button', { name: 'Remove', exact: true })
    .click()
  await expect.poll(async () => (await storedProject(page)).menu.elements.length).toBe(3)
  await page.locator('.menu-add-actions').getByRole('button', { name: 'Link', exact: true }).click()
  await expect.poll(async () => (await storedProject(page)).menu.elements.length).toBe(4)
  await page.locator('.menu-add-actions').getByRole('button', { name: 'Automatic pages', exact: true }).click()
  await expect.poll(async () => (await storedProject(page)).menu.elements.length).toBe(5)
  await page.locator('.page-button', { hasText: 'About page' }).click()
  await expect(preview(page).locator('main section')).toHaveCount(0)
  await preview(page).locator('[data-items="menu"]').click()
  await expect(page.getByRole('heading', { name: 'Menu for Test project' })).toBeVisible()
  await expect(items).toHaveCount(7)
  expect((await storedProject(page)).pages[0].content).toHaveLength(5)
  expect((await storedProject(page)).pages[3].content).toHaveLength(0)
})

test('Footer edits all element types, reorders, removes, and persists globally', async ({ editorPage: page }) => {
  await preview(page).locator('[data-items="footer"]').click()
  await expect(page.getByRole('heading', { name: 'Footer for Test project' })).toBeVisible()
  await page.getByLabel('Text content', { exact: true }).fill('Updated copyright')
  await page.getByLabel('URL', { exact: true }).fill('https://example.com/contact')
  await page.getByLabel('Profile URL', { exact: true }).fill('https://github.com/example')
  await page.getByPlaceholder('Custom HTML', { exact: true }).fill('<em>Updated footer note</em>')
  const footer = () => preview(page).getByRole('contentinfo', { name: 'Project footer' })
  await expect(footer()).toContainText('Updated copyright')
  await expect(footer().getByRole('link', { name: 'Contact', exact: true })).toHaveAttribute('href', 'https://example.com/contact')
  await expect(footer().getByRole('link', { name: 'github', exact: true })).toHaveAttribute('href', 'https://github.com/example')
  await expect(footer().locator('em')).toHaveText('Updated footer note')
  await expect(page.getByRole('button', { name: 'Move Copyright up', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Move Copyright down', exact: true }).click()
  await expect.poll(async () => (await storedProject(page)).footer.elements.map((element) => element.id)).toEqual(['footer-link', 'footer-text', 'footer-social', 'footer-html'])
  await expect(footer().locator(':scope > *').first()).toHaveText('Contact')
  await page
    .locator('.footer-element')
    .filter({ has: page.getByPlaceholder('Custom HTML', { exact: true }) })
    .getByRole('button', { name: 'Remove', exact: true })
    .click()
  await expect(footer().locator('em')).toHaveCount(0)
  await page.reload()
  await expect(footer()).toContainText('Updated copyright')
  await page.locator('.page-button', { hasText: 'About page' }).click()
  await expect(footer()).toContainText('Updated copyright')
  await expect(footer().locator(':scope > *').first()).toHaveText('Contact')
})

test('Footer adds link, text, HTML, and each supported social platform', async ({ editorPage: page }) => {
  await preview(page).locator('[data-items="footer"]').click()
  await expect(page.getByRole('heading', { name: 'Footer for Test project' })).toBeVisible()
  let count = 4
  for (const name of ['Link', 'Text', 'Custom HTML', 'facebook', 'twitter', 'instagram', 'linkedin', 'github', 'youtube']) {
    await page.locator('.settings').getByRole('button', { name, exact: true }).click()
    count += 1
    await expect.poll(async () => (await storedProject(page)).footer.elements.length).toBe(count)
    await expect(preview(page).locator('#footer > *')).toHaveCount(count)
  }
  const added = (await storedProject(page)).footer.elements.slice(4)
  expect(added.map((element) => element.type)).toEqual(['link', 'text', 'html', ...Array<string>(6).fill('social')])
  expect(added.slice(3).map((element) => element.socialPlatform)).toEqual(['facebook', 'twitter', 'instagram', 'linkedin', 'github', 'youtube'])
})
