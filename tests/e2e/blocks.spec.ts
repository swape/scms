import { readFile } from 'node:fs/promises'
import { elementsList } from '../../src/components/editor/elements-list'
import { expect, preview, seedProject, selectBlock, storedProject, test } from './fixtures'

for (const definition of elementsList) {
  test(`${definition.name} can be inserted, styled, persisted, and deleted`, async ({ editorPage: page }) => {
    const before = (await storedProject(page)).pages[0].content.length
    await page.getByRole('region', { name: 'Add element', exact: true }).getByRole('button', { name: definition.name, exact: true }).click()
    await expect.poll(async () => (await storedProject(page)).pages[0].content.length).toBe(before + 1)
    const block = (await storedProject(page)).pages[0].content.at(-1)!
    expect(block.type).toBe(definition.type)
    expect(block.order).toBe(before + 1)
    expect(block.pageId).toBe('home')
    const section = () => preview(page).locator(`section[data-id="${block.id}"]`)
    await expect(section()).toBeVisible()
    await page.getByRole('tab', { name: 'Style', exact: true }).click()
    await expect(page.getByLabel('Wrapper:', { exact: true })).toBeVisible()
    await page.getByLabel('Wrapper:', { exact: true }).selectOption('container')
    await expect(page.getByLabel('Padding unit', { exact: true })).toHaveValue('px')
    await page.getByLabel('Padding:', { exact: true }).fill('12')
    await page.getByLabel('Background color:', { exact: true }).selectOption('bg_2')
    await page.getByLabel('Text color:', { exact: true }).selectOption('text_2')
    const styled = () => preview(page).locator(`.scms_${block.id}`)
    await expect(styled()).toHaveCSS('padding-top', '12px')
    await expect(styled()).toHaveCSS('background-color', 'rgb(241, 245, 249)')
    await expect(styled()).toHaveCSS('color', 'rgb(71, 85, 105)')
    await expect(section()).toHaveClass(/container/)
    await expect
      .poll(async () => (await storedProject(page)).pages[0].content.at(-1)?.style)
      .toMatchObject({
        wrapper: 'container',
        paddingAll: '12px',
        backgroundColor: 'bg_2',
        textColor: 'text_2',
      })
    await page.reload()
    await expect(styled()).toHaveCSS('padding-top', '12px')
    const row = page.locator('.project-items li').filter({ has: page.locator(`[data-id="${block.id}"]`) })
    page.once('dialog', (dialog) => dialog.accept())
    await row.getByRole('button', { name: `Delete ${block.title}`, exact: true }).click()
    await expect(section()).toHaveCount(0)
    await expect.poll(async () => (await storedProject(page)).pages[0].content.length).toBe(before)
  })
}

